const express = require('express');
const router = express.Router();
const PDFDocument = require('pdfkit');
const { getDb } = require('../services/database');

const ERROR_TYPES = {
  wrong_account: {
    title: 'Account Does Not Belong to Me',
    body: (d) => `I have identified an account on my CIBIL report that does not belong to me. The account number ${d.accountNumber || '[ACCOUNT NUMBER]'} with ${d.lenderName || '[LENDER NAME]'} was never opened by me. This is likely a case of mixed files or identity error. I request immediate investigation and removal of this account from my credit report.`,
  },
  incorrect_balance: {
    title: 'Incorrect Outstanding Balance',
    body: (d) => `The outstanding balance reported for my account ${d.accountNumber || '[ACCOUNT NUMBER]'} with ${d.lenderName || '[LENDER NAME]'} is incorrect. The report shows ₹${d.reportedAmount || '[REPORTED AMOUNT]'} whereas the actual outstanding is ₹${d.actualAmount || '[ACTUAL AMOUNT]'}. I have attached supporting documents including my latest statement. Please correct this discrepancy.`,
  },
  duplicate_account: {
    title: 'Duplicate Account Entry',
    body: (d) => `My CIBIL report contains a duplicate entry for the same account with ${d.lenderName || '[LENDER NAME]'}. The account number ${d.accountNumber || '[ACCOUNT NUMBER]'} appears multiple times, artificially inflating my outstanding debt and reducing my credit score. Please investigate and remove the duplicate entry.`,
  },
  closed_showing_open: {
    title: 'Closed Account Showing as Open',
    body: (d) => `My account ${d.accountNumber || '[ACCOUNT NUMBER]'} with ${d.lenderName || '[LENDER NAME]'} was closed/paid in full on ${d.closureDate || '[CLOSURE DATE]'}. However, it still appears as "Open" or "Active" on my CIBIL report. I have the closure certificate/No Dues Certificate as proof. Please update the status to "Closed" immediately.`,
  },
  wrong_payment_status: {
    title: 'Incorrect Payment/DPD Status',
    body: (d) => `The Days Past Due (DPD) status for my account ${d.accountNumber || '[ACCOUNT NUMBER]'} with ${d.lenderName || '[LENDER NAME]'} is incorrectly reported. The report shows late payment for ${d.disputedMonth || '[MONTH/YEAR]'}, but I made the payment on time. I have bank statements showing the payment was made before the due date.`,
  },
  settled_but_paid: {
    title: 'Account Shows "Settled" but Was Paid in Full',
    body: (d) => `My account ${d.accountNumber || '[ACCOUNT NUMBER]'} with ${d.lenderName || '[LENDER NAME]'} shows a status of "Settled" on my CIBIL report. However, I paid the complete outstanding amount in full on ${d.paymentDate || '[PAYMENT DATE]'}. I have the payment receipt and No Dues Certificate. Please update the status to "Closed" as the full amount was paid.`,
  },
  unauthorized_inquiry: {
    title: 'Unauthorized Hard Inquiry',
    body: (d) => `My CIBIL report shows a hard inquiry by ${d.lenderName || '[LENDER NAME]'} on ${d.inquiryDate || '[INQUIRY DATE]'}. I never authorized this inquiry nor applied for any credit product with this institution. This unauthorized inquiry is negatively impacting my credit score. Please investigate and remove this inquiry from my report.`,
  },
};

router.get('/error-types', (req, res) => {
  const types = Object.entries(ERROR_TYPES).map(([key, val]) => ({
    value: key,
    label: val.title,
  }));
  res.json(types);
});

router.post('/generate-letter', (req, res) => {
  try {
    const { errorType, details } = req.body;
    const template = ERROR_TYPES[errorType];
    if (!template) return res.status(400).json({ error: 'Invalid error type' });

    const d = details || {};
    const db = getDb();
    db.prepare('INSERT INTO dispute_letters (error_type, details) VALUES (?, ?)')
      .run(errorType, JSON.stringify(d));

    const doc = new PDFDocument({ margin: 60, size: 'A4' });
    const chunks = [];
    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => {
      const pdfBuffer = Buffer.concat(chunks);
      res.setHeader('Content-Type', 'application/pdf');
      res.setHeader('Content-Disposition', `attachment; filename=CIBIL_Dispute_${errorType}.pdf`);
      res.send(pdfBuffer);
    });

    // Header
    doc.fontSize(10).fillColor('#666666')
      .text('DISPUTE LETTER — GENERATED BY CREDITSCORE RECOVERY COACH', { align: 'center' });
    doc.moveDown(0.5);
    doc.moveTo(60, doc.y).lineTo(535, doc.y).stroke('#cccccc');
    doc.moveDown(1);

    // Date and address
    const today = new Date().toLocaleDateString('en-IN', {
      day: 'numeric', month: 'long', year: 'numeric',
    });
    doc.fontSize(11).fillColor('#000000').text(today);
    doc.moveDown(0.5);
    doc.text('To,');
    doc.text('TransUnion CIBIL Limited');
    doc.text('One Indiabulls Centre, Tower 2A, Floor 19');
    doc.text('Senapati Bapat Marg, Elphinstone Road');
    doc.text('Mumbai — 400 013');
    doc.moveDown(1);

    // Subject
    doc.fontSize(12).font('Helvetica-Bold')
      .text(`Subject: Dispute — ${template.title}`);
    doc.moveDown(0.5);
    doc.font('Helvetica').fontSize(11);

    // Salutation
    doc.text('Dear Sir/Madam,');
    doc.moveDown(0.5);

    // Reference
    doc.text(`I am writing to formally dispute inaccurate information on my CIBIL credit report. My details are as follows:`);
    doc.moveDown(0.5);
    doc.text(`Full Name: ${d.fullName || '[YOUR FULL NAME]'}`);
    doc.text(`Date of Birth: ${d.dob || '[YOUR DATE OF BIRTH]'}`);
    doc.text(`PAN Number: ${d.pan || '[YOUR PAN NUMBER]'}`);
    doc.text(`CIBIL Score: ${d.cibilScore || '[YOUR CURRENT SCORE]'}`);
    doc.text(`Contact Number: ${d.phone || '[YOUR PHONE NUMBER]'}`);
    doc.text(`Email: ${d.email || '[YOUR EMAIL]'}`);
    doc.moveDown(0.5);

    // Dispute body
    doc.font('Helvetica-Bold').text('Nature of Dispute:');
    doc.font('Helvetica').moveDown(0.3);
    doc.text(template.body(d), { lineGap: 3 });
    doc.moveDown(0.5);

    // Legal basis
    doc.font('Helvetica-Bold').text('Legal Basis:');
    doc.font('Helvetica').moveDown(0.3);
    doc.text(
      'Under the Credit Information Companies (Regulation) Act, 2005, I have the right to dispute inaccurate information. ' +
      'As per Section 21, CIBIL is required to investigate the dispute within 30 days and correct or delete any information ' +
      'that cannot be verified. I request that you investigate this matter and provide me with the results in writing.',
      { lineGap: 3 }
    );
    doc.moveDown(0.5);

    // Enclosures
    doc.font('Helvetica-Bold').text('Enclosed Documents:');
    doc.font('Helvetica').moveDown(0.3);
    doc.text('1. Copy of my CIBIL report highlighting the disputed item');
    doc.text('2. Copy of my PAN card and Aadhaar card (identity proof)');
    doc.text('3. Supporting bank statements / payment receipts / closure certificates');
    doc.moveDown(1);

    // Closing
    doc.text('I request you to investigate this dispute at the earliest and update my credit report accordingly.');
    doc.moveDown(0.5);
    doc.text('Thanking you,');
    doc.text(`${d.fullName || '[YOUR FULL NAME]'}`);
    doc.text(`${d.address || '[YOUR ADDRESS]'}`);
    doc.moveDown(2);

    // Footer
    doc.fontSize(8).fillColor('#999999')
      .text('This letter was generated by CreditScore Recovery Coach for educational purposes. Verify all details before sending.', { align: 'center' });

    doc.end();
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Failed to generate dispute letter' });
  }
});

module.exports = router;
